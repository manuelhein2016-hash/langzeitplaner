const TABLES = { de: DE, en: EN };

let current = 'de';

export function setLang(l) {
  current = TABLES[l] ? l : 'de';
}
export function getLang() {
  return current;
}
export function t(key, ...args) {
  const v = TABLES[current][key];
  if (typeof v === 'function') return v(...args);
  return v ?? key;
}
